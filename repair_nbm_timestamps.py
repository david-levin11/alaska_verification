"""Repair known legacy NBM percentile timestamps into a NEW local model root.

Only use with archives entirely generated by the old validDate decoder.
Stop archive writers first. Copy mode leaves inputs unchanged; --in-place backs
up originals and installs replacements after validation. This repairs ONLY
selected affected datasets, not a replacement for the whole model directory.
Requires pandas and pyarrow. A failed run leaves an INCOMPLETE manifest.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys
from uuid import uuid4
from datetime import datetime, timezone
import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq

REPAIR_ID = 'nbm-interval-endpoint-v1'
MARKER = b'alaska_verification.timestamp_repair'
KEYS = ['station_id', 'init_time', 'valid_time', 'forecast_hour']
OFFSETS = {'nbmqmd': {'maxt':18, 'mint':18, 'precip6hr':6, 'precip24hr':24},
           'nbm': {'snow6hr':6, 'snow24hr':24, 'snow48hr':48, 'snow72hr':72}}


def digest(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda:f.read(1024*1024), b''):
            h.update(block)
    return h.hexdigest()


def inventory(root, models):
    paths=[]
    for model in models:
        for element,hours in OFFSETS[model].items():
            folder=root/model/element
            for path in sorted(folder.glob('*.parquet')):
                if not re.fullmatch(r'\d{4}_\d{2}_archive\.parquet',path.name):
                    raise ValueError(f'Unexpected archive filename: {path}')
                if path.is_symlink():
                    raise ValueError(f'Symlink input is not supported: {path}')
                paths.append((path,model,element,hours))
    if not paths:
        raise ValueError('No supported archive files found')
    return paths


def shifted_frame(df, hours):
    if not set(KEYS).issubset(df.columns):
        raise ValueError('Missing forecast key columns')
    if df[KEYS].isna().any().any():
        raise ValueError('Null forecast key')
    if df.duplicated(KEYS).any():
        raise ValueError('Duplicate input forecast keys; investigate before repair')
    for c in ('init_time','valid_time'):
        if not pd.api.types.is_datetime64_any_dtype(df[c]):
            raise ValueError(f'{c} must have a datetime dtype')
    lead=pd.to_numeric(df.forecast_hour,errors='raise')
    if (lead < 0).any() or (lead % 1 != 0).any():
        raise ValueError('Invalid forecast lead')
    if not ((df.valid_time-df.init_time).dt.total_seconds()==lead*3600).all():
        raise ValueError('Input lead and timestamps disagree')
    result=df.copy()
    delta=pd.Timedelta(hours=hours)
    for c in ('init_time','valid_time'):
        result[c]=df[c]+delta
    # Explicitly verify that reversing the change restores every original value.
    restored=result.copy()
    for c in ('init_time','valid_time'):
        restored[c]-=delta
    pd.testing.assert_frame_equal(df,restored,check_exact=True)
    return result


def write_marked(df,path):
    table=pa.Table.from_pandas(df,preserve_index=False)
    table=table.replace_schema_metadata({**(table.schema.metadata or {}),MARKER:REPAIR_ID.encode()})
    pq.write_table(table,path)
    pd.testing.assert_frame_equal(df.reset_index(drop=True),pd.read_parquet(path),check_exact=True)


def repair(source, output, models=('nbm','nbmqmd')):
    source=Path(source).resolve()
    output=Path(output).resolve()
    if not source.is_dir():
        raise ValueError('Source root must exist')
    if output==source or source in output.parents or output in source.parents:
        raise ValueError('Source and output roots must be separate, non-nested directories')
    if output.exists():
        raise ValueError('Output root must not already exist; refusing overwrite or repeat repair')
    state_path=source/'timestamp_repair_state.json'
    if state_path.exists():
        state=json.loads(state_path.read_text())
        if state.get('status')!='PREPARING' or output.parent!=Path(state.get('backup_root','')):
            raise ValueError('Archive root already has a repair state marker; refusing another shift')
    paths=inventory(source,models)
    initial_paths=[str(p) for p,_,_,_ in paths]
    # Catch marked inputs before creating any outputs.
    for path,_,_,_ in paths:
        if MARKER in (pq.read_metadata(path).metadata or {}):
            raise ValueError(f'Already repaired input: {path}')
    output.mkdir(parents=True)
    stage=output/'_staging'
    stage.mkdir()
    manifest={'repair_id':REPAIR_ID,'status':'INCOMPLETE','source_root':str(source),
              'output_root':str(output),'started_utc':datetime.now(timezone.utc).isoformat(),
              'assumption':'All inputs use the legacy decoder; no already-correct rows',
              'scope':'Only affected selected datasets; other model datasets are not copied',
              'inputs':[],'outputs':[]}
    def save():
        temp=output/'manifest.json.tmp'
        temp.write_text(json.dumps(manifest,indent=2)+'\n')
        temp.replace(output/'manifest.json')
    save()
    try:
        groups={}
        schemas={}
        for number,(path,model,element,hours) in enumerate(paths):
            before=digest(path)
            frame=pd.read_parquet(path)
            if not any(c.startswith(('qpf_p','maxt_p','mint_p','snow_p')) for c in frame.columns):
                raise ValueError(f'Not a percentile archive: {path}')
            schema=[(c,str(frame[c].dtype)) for c in frame.columns]
            dataset=(model,element)
            if dataset in schemas and schemas[dataset]!=schema:
                raise ValueError(f'Mixed schemas within {model}/{element}')
            schemas[dataset]=schema
            corrected=shifted_frame(frame,hours)
            utc_init=pd.to_datetime(corrected.init_time,utc=True)
            months=utc_init.dt.strftime('%Y_%m')
            entry={'path':str(path.relative_to(source)),'sha256':before,'rows':len(frame),
                   'shift_hours':hours,'destination_months':{str(k):int(v) for k,v in months.value_counts().items()},
                   'rows_leaving_filename_month':int((months!=path.name[:7]).sum())}
            for month,chunk in corrected.groupby(months,sort=True):
                key=(model,element,month)
                piece=stage/f'{number}-{month}.parquet'
                write_marked(chunk.reset_index(drop=True),piece)
                groups.setdefault(key,[]).append(piece)
            if digest(path)!=before:
                raise ValueError(f'Source changed during read: {path}')
            manifest['inputs'].append(entry)
            save()
            print(f'Staged {model}/{element}/{path.name}: {len(frame):,} rows, +{hours} h',flush=True)
        for (model,element,month),pieces in sorted(groups.items()):
            frames=[pd.read_parquet(p) for p in pieces]
            frame=pd.concat(frames,ignore_index=True)
            if frame.duplicated(KEYS).any():
                raise ValueError(f'Cross-file duplicate keys in {model}/{element}/{month}; nothing was silently dropped')
            if not (pd.to_datetime(frame.init_time,utc=True).dt.strftime('%Y_%m')==month).all():
                raise ValueError('Output month check failed')
            dest=output/model/element/f'{month}_archive.parquet'
            dest.parent.mkdir(parents=True,exist_ok=True)
            write_marked(frame,dest)
            manifest['outputs'].append({'path':str(dest.relative_to(output)),'rows':len(frame),'sha256':digest(dest)})
            save()
        if sum(x['rows'] for x in manifest['inputs'])!=sum(x['rows'] for x in manifest['outputs']):
            raise ValueError('Row conservation check failed (empty inputs also require review)')
        if [str(p) for p,_,_,_ in inventory(source,models)]!=initial_paths:
            raise ValueError('Source file inventory changed during repair')
        for entry in manifest['inputs']:
            if digest(source/entry['path'])!=entry['sha256']:
                raise ValueError(f"Source changed during repair: {entry['path']}")
        shutil.rmtree(stage)
        manifest['status']='COMPLETE'
        manifest['completed_utc']=datetime.now(timezone.utc).isoformat()
        save()
    except Exception as exc:
        manifest['error']=f'{type(exc).__name__}: {exc}'
        save()
        raise
    print(f"COMPLETE: {sum(x['rows'] for x in manifest['outputs']):,} rows; manifest: {output/'manifest.json'}")
    return manifest


STATE_FILE = 'timestamp_repair_state.json'


def save_json(path, data):
    temp=path.with_name(path.name+'.tmp')
    temp.write_text(json.dumps(data,indent=2)+'\n')
    temp.replace(path)


def rollback_install(backup):
    """Restore moved originals using the persisted install journal."""
    backup=Path(backup).resolve()
    journal_path=backup/'installation.json'
    journal=json.loads(journal_path.read_text())
    source=Path(journal['source_root'])
    if journal['status']=='INSTALLED':
        raise ValueError('Completed installation cannot be rolled back automatically after new writes')
    for rel in reversed(journal['datasets']):
        old=backup/'originals'/rel
        live=source/rel
        staged=backup/'corrected_staging'/rel
        if old.exists():
            if live.exists():
                if staged.exists():
                    raise ValueError(f'Ambiguous rollback state for {rel}; preserve all copies')
                staged.parent.mkdir(parents=True,exist_ok=True)
                live.rename(staged)
            live.parent.mkdir(parents=True,exist_ok=True)
            old.rename(live)
    journal['status']='ROLLED_BACK'
    save_json(journal_path,journal)
    state=source/STATE_FILE
    if state.exists() and json.loads(state.read_text()).get('backup_root')==str(backup):
        state.unlink()
    print(f'Original archives restored; diagnostic copies retained at {backup}')


def repair_in_place(source, models=('nbm','nbmqmd')):
    source=Path(source).resolve()
    if not source.is_dir():
        raise ValueError('Source root must exist')
    backup=source.parent/(source.name+'_timestamp_backup_'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'_'+uuid4().hex[:8])
    state=source/STATE_FILE
    # Persistent exclusive marker blocks concurrent or repeated in-place runs,
    # even after later archive appends strip Parquet metadata markers.
    with state.open('x') as f:
        json.dump({'status':'PREPARING','backup_root':str(backup)},f)
    journal={'status':'PREPARING','source_root':str(source),'datasets':[]}
    try:
        backup.mkdir()
        save_json(backup/'installation.json',journal)
        print(f'Backup location: {backup}',flush=True)
        result=repair(source,backup/'corrected_staging',models)
        datasets=sorted({str(Path(x['path']).parent) for x in result['inputs']})
        for rel in datasets:
            live=source/rel
            staged=backup/'corrected_staging'/rel
            if live.is_symlink() or not staged.is_dir():
                raise ValueError(f'Unsupported or empty dataset: {rel}')
            # Preserve auxiliary non-Parquet files as well as the original backup.
            for child in live.iterdir():
                if child.suffix != '.parquet':
                    if child.is_dir() or child.is_symlink():
                        raise ValueError(f'Unexpected nested directory or link: {child}')
                    shutil.copy2(child,staged/child.name)
        # Final source check immediately before the first directory move.
        for entry in result['inputs']:
            if digest(source/entry['path'])!=entry['sha256']:
                raise ValueError('Archive changed; stop cron and retry with an unchanged source')
        journal.update(status='INSTALLING',datasets=datasets)
        save_json(backup/'installation.json',journal)
        for rel in datasets:
            live=source/rel
            old=backup/'originals'/rel
            staged=backup/'corrected_staging'/rel
            old.parent.mkdir(parents=True,exist_ok=True)
            live.rename(old)
            staged.rename(live)
        for entry in result['outputs']:
            if digest(source/entry['path'])!=entry['sha256']:
                raise ValueError('Installed archive hash mismatch')
        for entry in result['inputs']:
            if digest(backup/'originals'/entry['path'])!=entry['sha256']:
                raise ValueError('Backup archive hash mismatch')
        # Record completion in the journal first. If the final marker update is
        # interrupted, a retry is still blocked and originals remain preserved.
        journal['status']='INSTALLED'
        save_json(backup/'installation.json',journal)
        save_json(state,{'status':'INSTALLED','backup_root':str(backup),'repair_id':REPAIR_ID})
    except BaseException:
        if (backup/'installation.json').exists():
            persisted=json.loads((backup/'installation.json').read_text())
            if persisted['status']!='INSTALLED':
                rollback_install(backup)
        else:
            state.unlink(missing_ok=True)
        raise
    print(f'INSTALLED: corrected archives at {source}; originals at {backup / "originals"}')
    print('Deploy the fixed decoder before resuming cron.')
    return backup


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root')
    mode=parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--output-root',help='Write separate corrected copies into a new directory')
    mode.add_argument('--in-place',action='store_true',help='Back up originals and install corrected archives; stop cron first')
    mode.add_argument('--rollback-backup',help='Recover an interrupted, incomplete installation using its backup directory')
    parser.add_argument('--models',nargs='+',choices=sorted(OFFSETS),default=['nbm','nbmqmd'])
    args=parser.parse_args()
    if not args.rollback_backup and not args.source_root:
        parser.error('--source-root is required')
    try:
        models=tuple(dict.fromkeys(args.models))
        if args.rollback_backup:
            rollback_install(args.rollback_backup)
        elif args.in_place:
            repair_in_place(args.source_root,models)
        else:
            repair(args.source_root,args.output_root,models)
    except Exception as exc:
        print(f'Repair failed: {exc}',file=sys.stderr)
        return 1
    return 0


if __name__=='__main__':raise SystemExit(main())
